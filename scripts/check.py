"""Lint and offline-test Eds Custom Addon (Lua 5.1 / WotLK, no client)."""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOC_NAME = "Eds Custom Addon.toc"
ADDON_NAME = "Eds Custom Addon"
SOUND_EXTS = {".wav", ".mp3"}
DEFAULT_SOUND_DURATION = 0.5

BANNED = [
    (r"\bIsInGroup\s*\(", "IsInGroup is MoP+; use GetNumPartyMembers/GetNumRaidMembers"),
    (r"\bIsInRaid\s*\(", "IsInRaid is MoP+; use GetNumRaidMembers"),
    (r"\bGetNumGroupMembers\s*\(", "GetNumGroupMembers is MoP+"),
    (r"\bGROUP_ROSTER_UPDATE\b", "GROUP_ROSTER_UPDATE is MoP+"),
    (r"\bC_Timer\.", "C_Timer is not in 3.3.5"),
    (r'SendChatMessage\s*\(\s*"/xp', "Server XP commands use a dot prefix, not /xp"),
]

def lua_file(rel: str) -> Path:
    return ROOT.joinpath(*rel.replace("\\", "/").split("/"))


def posix(path: Path) -> str:
    return path.resolve().as_posix()


failures = 0


def fail(msg: str) -> None:
    global failures
    failures += 1
    print(f"  FAIL  {msg}")


def ok(msg: str) -> None:
    print(f"  PASS  {msg}")


def sound_category(filename: str) -> str:
    stem = Path(filename).stem.lower()
    if stem.startswith("kill-"):
        return "kill"
    if stem.startswith("lowhp-"):
        return "lowhp"
    return "default"


def probe_sound_duration(path: Path) -> float:
    """Return audio length in seconds; fall back to DEFAULT_SOUND_DURATION."""
    try:
        from mutagen import File as MutagenFile

        audio = MutagenFile(str(path))
        length = getattr(getattr(audio, "info", None), "length", None)
        if length is not None and float(length) > 0:
            return round(float(length), 3)
        print(f"  NOTE  duration probe failed for {path.name}; using {DEFAULT_SOUND_DURATION}s")
    except Exception as exc:  # noqa: BLE001 - lint continues with fallback
        print(f"  NOTE  duration probe failed for {path.name}: {exc}; using {DEFAULT_SOUND_DURATION}s")
    return DEFAULT_SOUND_DURATION


def generate_sound_manifest() -> tuple[dict[str, list[str]], dict[str, float]]:
    """Scan Sounds/ and write manifest.lua (WoW cannot list dirs at runtime)."""
    sounds_dir = ROOT / "Sounds"
    pools: dict[str, list[str]] = {"default": [], "lowhp": [], "kill": []}
    durations: dict[str, float] = {}
    if sounds_dir.is_dir():
        for entry in sorted(sounds_dir.iterdir()):
            if entry.is_file() and entry.suffix.lower() in SOUND_EXTS:
                path = (
                    "Interface\\\\AddOns\\\\"
                    + ADDON_NAME
                    + "\\\\Sounds\\\\"
                    + entry.name
                )
                pools[sound_category(entry.name)].append(path)
                durations[path] = probe_sound_duration(entry)

    def pool_lines(name: str, paths: list[str]) -> list[str]:
        block = [f"{name} = {{"]
        for index, path in enumerate(paths, start=1):
            block.append(f'    [{index}] = "{path}",')
        block.append("}")
        return block

    def duration_lines(entries: dict[str, float]) -> list[str]:
        block = ["WindfurySoundDurations = {"]
        for path, seconds in entries.items():
            block.append(f'    ["{path}"] = {seconds},')
        block.append("}")
        return block

    lines = ["-- Auto-generated by scripts/check.py. Do not edit."]
    lines.extend(pool_lines("WindfurySounds", pools["default"]))
    lines.extend(pool_lines("WindfurySoundsLowHp", pools["lowhp"]))
    lines.extend(pool_lines("WindfurySoundsKill", pools["kill"]))
    lines.extend(duration_lines(durations))
    manifest = sounds_dir / "manifest.lua"
    manifest.parent.mkdir(parents=True, exist_ok=True)
    manifest.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return pools, durations


def toc_lua_files() -> list[str]:
    toc = ROOT / TOC_NAME
    if not toc.exists():
        fail(f"missing {TOC_NAME}")
        return []
    files = []
    for line in toc.read_text(encoding="utf-8").splitlines():
        raw = line.strip()
        if raw.lower().endswith(".lua") and not raw.startswith("#"):
            files.append(raw.replace("\\", "/"))
    return files


def lint_toc() -> None:
    print("lint: toc")
    toc = ROOT / TOC_NAME
    text = toc.read_text(encoding="utf-8")
    if "## Interface: 30300" in text:
        ok("Interface 30300")
    else:
        fail("TOC must declare ## Interface: 30300")
    if "SavedVariablesPerCharacter: EdsCustomAddonDB" in text:
        ok("SavedVariablesPerCharacter declared")
    else:
        fail("missing SavedVariablesPerCharacter")

    files = toc_lua_files()
    expected = [
        "Core/Util.lua",
        "Core/Config.lua",
        "Core/Core.lua",
        "Core/UI.lua",
        "Modules/PartyXP/PartyXP.lua",
        "Sounds/manifest.lua",
        "Modules/Windfury/Windfury.lua",
    ]
    if files == expected:
        ok("TOC load order")
    else:
        fail(f"TOC load order {files} != {expected}")

    for rel in files:
        path = lua_file(rel)
        if path.exists():
            ok(f"exists {rel}")
        else:
            fail(f"missing {rel}")


def lint_lua_static() -> None:
    print("lint: static")
    for rel in toc_lua_files():
        path = lua_file(rel)
        text = path.read_text(encoding="utf-8")
        if "\t" in text:
            fail(f"{rel} contains tabs")
        else:
            ok(f"{rel} no tabs")
        for i, line in enumerate(text.splitlines(), 1):
            stripped = line.split("--", 1)[0]
            for pattern, reason in BANNED:
                if re.search(pattern, stripped):
                    fail(f"{rel}:{i}: {reason}")
    ui = (ROOT / "Core" / "UI.lua").read_text(encoding="utf-8")
    if "RegisterModule" in ui:
        fail("Core/UI.lua must not RegisterModule (panel is not a feature module)")
    else:
        ok("UI.lua is not a feature module")
    party = (ROOT / "Modules" / "PartyXP" / "PartyXP.lua").read_text(encoding="utf-8")
    if "RegisterModule" in party:
        ok("PartyXP registers itself")
    else:
        fail("PartyXP.lua does not call RegisterModule")
    windfury = (ROOT / "Modules" / "Windfury" / "Windfury.lua").read_text(encoding="utf-8")
    if "RegisterModule" in windfury:
        ok("Windfury registers itself")
    else:
        fail("Windfury.lua does not call RegisterModule")


def lint_syntax(lua) -> None:
    print("lint: syntax")
    for rel in toc_lua_files():
        path = posix(lua_file(rel))
        try:
            lua.execute(f'assert(loadfile("{path}"))')
            ok(f"syntax {rel}")
        except Exception as exc:
            fail(f"syntax {rel}: {exc}")


def load_addon(lua, env_path: Path) -> None:
    lua.eval("dofile")(posix(env_path))
    for rel in toc_lua_files():
        lua.eval("dofile")(posix(lua_file(rel)))


def fire_loaded(lua) -> None:
    addon = lua.eval("EdsCustomAddon")
    addon.OnEvent(addon, "ADDON_LOADED", "Eds Custom Addon")


def last_sent(lua) -> list[str]:
    sent = lua.eval("wow.sent")
    out = []
    for i in range(1, len(sent) + 1):
        item = sent[i]
        msg = getattr(item, "msg", None)
        out.append(msg if msg is not None else str(item))
    return out


def last_sent_types(lua) -> list[str]:
    sent = lua.eval("wow.sent")
    out = []
    for i in range(1, len(sent) + 1):
        item = sent[i]
        out.append(getattr(item, "chatType", None))
    return out


def last_sounds(lua) -> list[str]:
    sounds = lua.eval("wow.sounds")
    return [sounds[i] for i in range(1, len(sounds) + 1)]


def last_prints(lua) -> list[str]:
    prints = lua.eval("wow.prints")
    return [prints[i] for i in range(1, len(prints) + 1)]


def last_combat_text(lua) -> list[dict]:
    entries = lua.eval("wow.combatText")
    out = []
    for i in range(1, len(entries) + 1):
        entry = entries[i]
        out.append({
            "msg": entry.msg,
            "r": entry.r,
            "g": entry.g,
            "b": entry.b,
            "displayType": entry.displayType,
        })
    return out


def test_addon(lua) -> None:
    print("test: load + behavior")
    addon = lua.eval("EdsCustomAddon")
    wow = lua.eval("wow")

    fire_loaded(lua)
    if addon.loaded:
        ok("ADDON_LOADED initializes addon")
    else:
        fail("ADDON_LOADED did not set loaded")

    party = addon.GetModule(addon, "PartyXP")
    if party is None:
        fail("PartyXP not registered")
        return
    ok("PartyXP registered")

    if party.enabled:
        ok("PartyXP enabled by default")
    else:
        fail("PartyXP should default to enabled")

    if addon.ui is None:
        fail("CreateUI did not run")
    else:
        ok("ECA_Panel created")
        if addon.ui.shown:
            fail("panel should start hidden")
        else:
            ok("panel starts hidden")
        if addon.ui.windfuryPath:
            ok("panel has Windfury path box")
            box = addon.ui.windfuryPath
            box.SetText(box, "Interface\\AddOns\\Eds Custom Addon\\Sounds\\proc.wav")
            lost = box.scripts.OnEditFocusLost
            if lost:
                lost(box)
            path = addon.db.modules.Windfury.soundFile
            if path and "proc.wav" in path:
                ok("GUI sound path saves to db")
            else:
                fail(f"GUI path save got {path}")
        else:
            fail("panel missing windfuryPath edit box")
        if addon.ui.partyxpPause:
            ok("panel has PartyXP pause checkbox")
            wow.resetChat()
            wow.state.xpDisabled = False
            check = addon.ui.partyxpPause
            check.SetChecked(check, 1)
            check.scripts.OnClick(check)
            if addon.db.modules.PartyXP.paused:
                ok("GUI pause saves to db")
            else:
                fail("GUI pause did not set paused")
            sent = last_sent(lua)
            if sent == [".xp disable"]:
                ok("GUI pause disables XP")
            else:
                fail(f"GUI pause sent {sent}")
            check.SetChecked(check, None)
            check.scripts.OnClick(check)
            if not addon.db.modules.PartyXP.paused:
                ok("GUI unpause clears paused")
            else:
                fail("GUI unpause did not clear paused")
        else:
            fail("panel missing partyxpPause checkbox")
        if addon.ui.partyxpForce:
            ok("panel has PartyXP force checkbox")
            wow.resetChat()
            wow.setSolo()
            wow.state.xpDisabled = True
            force = addon.ui.partyxpForce
            force.SetChecked(force, 1)
            force.scripts.OnClick(force)
            if party.forceXP:
                ok("GUI force sets session flag")
            else:
                fail("GUI force did not set forceXP")
            sent = last_sent(lua)
            if sent == [".xp enable"]:
                ok("GUI force enables XP when solo")
            else:
                fail(f"GUI force sent {sent}")
            force.SetChecked(force, None)
            force.scripts.OnClick(force)
            if not party.forceXP:
                ok("GUI unforce clears session flag")
            else:
                fail("GUI unforce did not clear forceXP")
            wow.resetChat()
            wow.setSolo()
            wow.state.xpDisabled = True
            lua.execute("EdsCustomAddon.db.modules.PartyXP.paused = true")
            addon.ui.partyxpPause.SetChecked(addon.ui.partyxpPause, 1)
            addon.ui.partyxpPause.scripts.OnClick(addon.ui.partyxpPause)
            force.SetChecked(force, 1)
            force.scripts.OnClick(force)
            if not addon.db.modules.PartyXP.paused and party.forceXP:
                ok("GUI force clears persisted pause")
            else:
                fail("force/pause not mutually exclusive")
            force.SetChecked(force, None)
            force.scripts.OnClick(force)
            lua.execute("EdsCustomAddon.db.modules.PartyXP.paused = false")
        else:
            fail("panel missing partyxpForce checkbox")
        if addon.ui.windfuryTest:
            ok("panel has Windfury test button")
        else:
            fail("panel missing windfuryTest button")
        if addon.ui.windfuryProcPoolButtons:
            ok("panel has proc pool buttons")
            wow.resetChat()
            lua.execute("""
                WindfurySoundsKill = { [1] = "Sounds/kill-preview.mp3" }
                local wf = EdsCustomAddon:GetModule("Windfury")
                wf.soundBusyUntil = nil; wf.soundBusyIsKill = nil
                wf:SetPreviewProcPool("kill")
            """)
            addon.ui.windfuryTest.scripts.OnClick(addon.ui.windfuryTest)
            sounds = last_sounds(lua)
            if sounds and sounds[-1] == "Sounds/kill-preview.mp3":
                ok("Test proc uses selected kill pool")
            else:
                fail(f"Test proc pool play {sounds}")
            lua.execute("""
                local wf = EdsCustomAddon:GetModule("Windfury")
                wf.lastStreakProc = nil
                wf.streakCount = nil
                wf:SetPreviewProcPool("default")
            """)
            wow.resetChat()
        else:
            fail("panel missing windfuryProcPoolButtons")
        sound_rows = addon.ui.windfurySoundRows
        sound_test = addon.ui.windfurySoundTest
        if sound_rows and len(sound_rows) > 0 and sound_test:
            ok("panel has sound preview list")
            wow.resetChat()
            lua.execute(
                'local wf = EdsCustomAddon:GetModule("Windfury"); '
                "if wf then wf.soundBusyUntil = nil; wf.soundBusyIsKill = nil end"
            )
            sound_test.scripts.OnClick(sound_test)
            sounds = last_sounds(lua)
            manifest = lua.eval("WindfurySounds")
            if sounds and manifest and sounds[-1] == manifest[1]:
                ok("Test sound button plays selected manifest entry")
            else:
                fail(f"Test sound played {sounds}, expected {manifest[1] if manifest else None}")
            wow.resetChat()
            lua.execute(
                'local wf = EdsCustomAddon:GetModule("Windfury"); '
                "if wf then wf.soundBusyUntil = nil; wf.soundBusyIsKill = nil end"
            )
            sound_rows[2].scripts.OnClick(sound_rows[2])
            sound_test.scripts.OnClick(sound_test)
            sounds = last_sounds(lua)
            if sounds and manifest and sounds[-1] == manifest[2]:
                ok("Test sound button plays newly selected entry")
            else:
                fail(f"selected sound play {sounds}, expected {manifest[2] if manifest else None}")
        elif addon.ui.windfurySoundEmpty:
            ok("panel shows empty sound list message")
        else:
            fail("panel missing windfury sound list")

    wow.resetChat()
    wow.setSolo()
    wow.state.xpDisabled = False
    party.SyncXP(party)
    sent = last_sent(lua)
    if sent == [".xp disable"]:
        ok("solo sends .xp off")
    else:
        fail(f"solo sent {sent}, expected ['.xp disable']")
    types = last_sent_types(lua)
    if types == ["WHISPER"]:
        ok("alive sync uses WHISPER not SAY")
    else:
        fail(f"alive sync types {types}, expected ['WHISPER']")

    wow.resetChat()
    party.SyncXP(party)
    sent = last_sent(lua)
    if sent == []:
        ok("solo idempotent (no second .xp off)")
    else:
        fail(f"solo second sync sent {sent}")

    wow.resetChat()
    wow.setParty(True)
    wow.state.xpDisabled = True
    party.SyncXP(party)
    sent = last_sent(lua)
    if sent == [".xp enable"]:
        ok("online party member sends .xp on")
    else:
        fail(f"online party sent {sent}, expected ['.xp enable']")

    wow.resetChat()
    wow.setParty(False)
    wow.state.xpDisabled = False
    party.SyncXP(party)
    sent = last_sent(lua)
    if sent == [".xp disable"]:
        ok("offline-only party sends .xp off")
    else:
        fail(f"offline party sent {sent}, expected ['.xp disable']")

    wow.resetChat()
    wow.setRaidSelfOnly()
    wow.state.xpDisabled = False
    party.SyncXP(party)
    sent = last_sent(lua)
    if sent == [".xp disable"]:
        ok("raid of self only sends .xp off")
    else:
        fail(f"raid-self sent {sent}, expected ['.xp disable']")

    wow.resetChat()
    wow.setRaidWithPartner(True)
    wow.state.xpDisabled = True
    party.SyncXP(party)
    sent = last_sent(lua)
    if sent == [".xp enable"]:
        ok("raid with online partner sends .xp on")
    else:
        fail(f"raid-partner sent {sent}, expected ['.xp enable']")

    wow.resetChat()
    wow.setRaidWithPartner(False)
    wow.state.xpDisabled = False
    party.SyncXP(party)
    sent = last_sent(lua)
    if sent == [".xp disable"]:
        ok("raid partner offline sends .xp off")
    else:
        fail(f"raid-offline-partner sent {sent}, expected ['.xp disable']")

    wow.resetChat()
    wow.state.ghost = True
    wow.setParty(False)
    wow.state.xpDisabled = False
    party.SyncXP(party)
    sent = last_sent(lua)
    types = last_sent_types(lua)
    if sent == [".xp disable"] and types == ["WHISPER"] and wow.state.xpDisabled:
        ok("ghost party-leave still sends .xp off via WHISPER")
    else:
        fail(f"ghost whisper sent {sent} types {types} xpDisabled={wow.state.xpDisabled}")

    wow.resetChat()
    wow.state.playerName = ""
    wow.state.ghost = True
    wow.setSolo()
    wow.state.xpDisabled = False
    party.SyncXP(party)
    sent = last_sent(lua)
    if sent == [] and not wow.state.xpDisabled:
        ok("ghost SAY fallback is dropped (no name, no group)")
    else:
        fail(f"ghost SAY-only sent {sent} xpDisabled={wow.state.xpDisabled}")

    wow.state.playerName = "Ed"
    wow.state.ghost = False
    wow.resetChat()
    addon.OnEvent(addon, "PLAYER_ALIVE")
    sent = last_sent(lua)
    if sent == []:
        ok("PLAYER_ALIVE is debounced")
    else:
        fail(f"PLAYER_ALIVE sent immediately {sent}")
    wow.flushDebounce()
    sent = last_sent(lua)
    types = last_sent_types(lua)
    if sent == [".xp disable"] and types == ["WHISPER"] and wow.state.xpDisabled:
        ok("PLAYER_ALIVE retries .xp off after rez")
    else:
        fail(f"PLAYER_ALIVE after tick sent {sent} types {types} xpDisabled={wow.state.xpDisabled}")

    addon.DisableModule(addon, "PartyXP")
    if not party.enabled:
        ok("DisableModule turns PartyXP off")
    else:
        fail("DisableModule left PartyXP enabled")
    wow.resetChat()
    wow.setParty(True)
    wow.state.xpDisabled = True
    party.SyncXP(party)
    sent = last_sent(lua)
    if sent == []:
        ok("disabled module does not send .xp")
    else:
        fail(f"disabled module sent {sent}")

    addon.EnableModule(addon, "partyxp")
    if party.enabled:
        ok("EnableModule is case-insensitive")
    else:
        fail("GetModule/EnableModule failed for 'partyxp'")

    wow.resetChat()
    wow.setSolo()
    wow.state.xpDisabled = False
    party.RequestSync(party)
    sent = last_sent(lua)
    if sent == []:
        ok("RequestSync is debounced (no immediate send)")
    else:
        fail(f"debounced sync sent immediately: {sent}")
    wow.flushDebounce()
    sent = last_sent(lua)
    if sent == [".xp disable"]:
        ok("debounce fires after 0.2s")
    else:
        fail(f"after tick sent {sent}, expected ['.xp disable']")

    wow.resetChat()
    wow.setSolo()
    wow.state.xpDisabled = False
    party.RequestSync(party)
    party.RequestSync(party)
    wow.flushDebounce()
    sent = last_sent(lua)
    if sent == [".xp disable"]:
        ok("burst RequestSync sends once")
    else:
        fail(f"burst debounce sent {sent}")

    db = lua.eval("EdsCustomAddonDB")
    if db.modules.PartyXP.enabled:
        ok("enabled state persisted to SavedVariables")
    else:
        fail("db.modules.PartyXP.enabled not true after EnableModule")

    addon.SlashHandler(addon, "debug")
    if addon.db.debug:
        ok("slash debug enables db.debug")
    else:
        fail("slash debug did not toggle on")

    shown_before = bool(addon.ui.shown)
    addon.SlashHandler(addon, "ui")
    if bool(addon.ui.shown) != shown_before:
        ok("slash ui toggles panel")
    else:
        fail("slash ui did not toggle panel visibility")
    addon.SlashHandler(addon, "ui")
    if bool(addon.ui.shown) == shown_before:
        ok("slash ui toggles panel back")
    else:
        fail("slash ui second toggle did not restore visibility")

    wow.resetChat()
    addon.SlashHandler(addon, "partyxp status")
    prints = last_prints(lua)
    if prints and "PartyXP" in prints[-1]:
        ok("slash partyxp status prints")
    else:
        fail(f"status prints {prints}")

    wow.resetChat()
    wow.setParty(True)
    wow.state.xpDisabled = False
    lua.execute("EdsCustomAddon.db.modules.PartyXP.paused = true")
    party = lua.eval('EdsCustomAddon:GetModule("PartyXP")')
    party.SyncXP(party)
    sent = last_sent(lua)
    if sent == [".xp disable"]:
        ok("paused overrides party and disables XP")
    else:
        fail(f"paused party sent {sent}")

    wow.resetChat()
    wow.setParty(True)
    wow.state.xpDisabled = False
    lua.execute("EdsCustomAddon.db.modules.PartyXP.paused = false")
    addon.SlashHandler(addon, "partyxp pause")
    sent = last_sent(lua)
    prints = last_prints(lua)
    if sent == [".xp disable"] and prints and "paused" in prints[-1].lower():
        ok("partyxp pause disables immediately")
    else:
        fail(f"partyxp pause sent {sent} prints {prints}")

    wow.resetChat()
    wow.setParty(True)
    wow.state.xpDisabled = True
    lua.execute("EdsCustomAddon.db.modules.PartyXP.paused = false")
    addon.SlashHandler(addon, "partyxp unpause")
    sent = last_sent(lua)
    prints = last_prints(lua)
    if sent == [".xp enable"]:
        ok("unpause in party enables XP")
    else:
        fail(f"unpause sent {sent}")
    if prints and "unpaused" in prints[-1] and "wantXP=on" in prints[-1]:
        ok("unpause prints wantXP=on when partner online")
    else:
        fail(f"unpause status prints {prints}")

    wow.resetChat()
    wow.setParty(False)
    wow.state.xpDisabled = True
    lua.execute("EdsCustomAddon.db.modules.PartyXP.paused = true")
    addon.SlashHandler(addon, "partyxp unpause")
    sent = last_sent(lua)
    prints = last_prints(lua)
    if sent == []:
        ok("unpause with offline party sends nothing when XP already off")
    else:
        fail(f"offline party unpause sent {sent}")
    if prints and "wantXP=off" in prints[-1]:
        ok("unpause explains wantXP=off for offline party")
    else:
        fail(f"offline unpause status prints {prints}")

    wow.resetChat()
    lua.execute("EdsCustomAddon.db.modules.PartyXP.paused = true")
    addon.SlashHandler(addon, "partyxp status")
    prints = last_prints(lua)
    if prints and "paused=yes" in prints[-1]:
        ok("partyxp status shows paused=yes")
    else:
        fail(f"paused status prints {prints}")

    wow.resetChat()
    wow.setSolo()
    wow.state.xpDisabled = True
    lua.execute("EdsCustomAddon.db.modules.PartyXP.paused = false")
    party = lua.eval('EdsCustomAddon:GetModule("PartyXP")')
    party.SetForceXP(party, True)
    sent = last_sent(lua)
    if sent == [".xp enable"]:
        ok("force overrides solo and enables XP")
    else:
        fail(f"force solo sent {sent}")

    wow.resetChat()
    wow.setSolo()
    wow.state.xpDisabled = True
    party.SetForceXP(party, False)
    addon.SlashHandler(addon, "partyxp force")
    prints = last_prints(lua)
    sent = last_sent(lua)
